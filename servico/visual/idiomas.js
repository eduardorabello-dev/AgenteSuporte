  const INDICE = { pt: 0, es: 1, en: 2 };
  const TITULOS = {};
  for (const chave of ["inicio.titulo", "chat.titulo", "painel.titulo"]) for (const texto of D[chave]) TITULOS[texto] = chave;
  const idioma = () => (window.Preferencias ? window.Preferencias.ler().idioma : "pt");

  function t(chave, vars) {
    const linha = D[chave];
    let texto = linha ? (linha[INDICE[idioma()]] ?? linha[0]) : chave;
    if (vars) for (const [k, v] of Object.entries(vars)) texto = texto.split(`{${k}}`).join(String(v));
    return texto;
  }

